const assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.BUILDTRAIL_PLAYWRIGHT||'playwright');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  const page=await browser.newPage(), errors=[], external=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(/^https?:/.test(r.url()))external.push(r.url());});
  await page.goto(pathToFileURL(process.argv[2]).href);
  assert.equal(await page.evaluate(()=>window.buildtrailInjected),undefined);
  assert.equal(await page.locator('script').count(),1);
  assert.equal(await page.locator('#query').inputValue(),'a+b');
  assert(await page.locator('#case').isChecked());
  assert.equal(await page.locator('#severity').inputValue(),'warning');
  assert.equal(await page.locator('#side').inputValue(),'after');
  assert(await page.locator('body').evaluate(e=>e.classList.contains('light')));
  assert.match(await page.locator('#search-status').innerText(),/^2 matches/);
  await page.locator('#next-match').click();
  assert.match(await page.locator('#search-status').innerText(),/Match 1\/2 · before line/);
  assert.equal(await page.locator('mark.current').innerText(),'a+b');
  await page.keyboard.press('F3');
  assert.match(await page.locator('#search-status').innerText(),/Match 2\/2 · after line/);
  await page.keyboard.press('Shift+F3');
  assert.match(await page.locator('#search-status').innerText(),/Match 1\/2/);
  await page.locator('#prev-match').click();
  assert.match(await page.locator('#search-status').innerText(),/Match 2\/2/);
  await page.locator('#query').fill('SHARED');
  await page.waitForTimeout(250);
  assert.match(await page.locator('#search-status').innerText(),/^1 matches/);
  await page.locator('#case').uncheck();
  assert.match(await page.locator('#search-status').innerText(),/^2 matches/);
  await page.locator('#query').fill('İ');await page.waitForTimeout(250);
  assert.match(await page.locator('#search-status').innerText(),/^2 matches/);
  await page.locator('#query').fill('x');await page.waitForTimeout(250);
  assert.match(await page.locator('#search-status').innerText(),/^2000\+ matches/);
  await page.locator('#query').fill('</script><script>');await page.waitForTimeout(250);
  assert.equal(await page.evaluate(()=>window.buildtrailInjected),undefined);
  await page.locator('#clear').click();assert.equal(await page.locator('mark').count(),0);
  assert.match(await page.locator('#issue-status').innerText(),/^1 error\/warning/);
  await page.locator('#next-issue').click();
  assert.match(await page.locator('#issue-status').innerText(),/after line \d+ · warning/);
  await page.locator('#severity').selectOption('error');
  await page.locator('#next-issue').click();
  assert.match(await page.locator('#issue-status').innerText(),/after line 1 · error/);
  await page.locator('#side').selectOption('before');
  assert.match(await page.locator('#issue-status').innerText(),/^0 error\/warning/);
  await page.locator('#side').selectOption('');await page.locator('#severity').selectOption('');
  await page.keyboard.press('Control+ArrowDown');
  assert.match(await page.locator('#issue-status').innerText(),/^Issue 1\/3/);
  await page.keyboard.press('Control+ArrowUp');
  assert.match(await page.locator('#issue-status').innerText(),/^Issue 3\/3/);
  await page.locator('#next-change').click();assert.equal(await page.locator('.active-change').count(),1);
  await page.locator('#prev-change').click();assert.equal(await page.locator('.active-change').count(),1);
  await page.locator('#theme').click();assert(!(await page.locator('body').evaluate(e=>e.classList.contains('light'))));
  // Give both panes enough rows to exercise scrolling without changing report code.
  await page.evaluate(()=>{for(const pane of document.querySelectorAll('.pane'))pane.style.height='50px';document.getElementById('before').scrollTop=55;});
  await page.waitForTimeout(100);
  assert(await page.evaluate(()=>Math.abs(document.getElementById('before').scrollTop-document.getElementById('after').scrollTop)<2));
  await page.keyboard.press('Control+f');assert(await page.locator('#query').evaluate(e=>e===document.activeElement));
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  const nojs=await browser.newContext({javaScriptEnabled:false});const fallback=await nojs.newPage();
  await fallback.goto(pathToFileURL(process.argv[2]).href);assert((await fallback.locator('#after').innerText()).includes('compiler error'));
  await nojs.close();
  console.log('Side-by-side HTML passed: settings, literal/Unicode search, cap, keys, issue/change navigation, filters, scrolling, theme, escaped logs, offline requests and no-JS fallback.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
